/**
 * archive legal/*.html → src/content/legal/*.ts (원본: repo 밖 스냅샷)
 * node scripts/generate-legal-content.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { resolveLegacyHtmlArchiveRoot } = require("./legacy-html-archive-path.cjs");

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const archiveRoot = resolveLegacyHtmlArchiveRoot(root);
const slugs = [
  "terms-of-service",
  "privacy-policy",
  "refund-policy",
  "copyright",
  "service-payment-guide",
];

function extractArticle(html) {
  const m = html.match(/<main[^>]*class="[^"]*ping-doc-article[^"]*"[^>]*>([\s\S]*?)<\/main>/i);
  if (!m) throw new Error("main.ping-doc-article not found");
  return m[1].trim();
}

function extractTitle(articleHtml) {
  const m = articleHtml.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  return m ? m[1].replace(/<[^>]+>/g, "").trim() : "";
}

const outDir = path.join(root, "src", "content", "legal");
fs.mkdirSync(outDir, { recursive: true });

const indexLines = ["/** Auto-generated by scripts/generate-legal-content.mjs */", ""];

for (const slug of slugs) {
  const raw = fs.readFileSync(path.join(archiveRoot, "legal", `${slug}.html`), "utf8");
  const articleHtml = extractArticle(raw);
  const title = extractTitle(articleHtml);
  const varName = slug.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const outPath = path.join(outDir, `${slug}.ts`);
  fs.writeFileSync(
    outPath,
    `/** @generated — 원본 legacy-html/legal/${slug}.html */\nexport const title = ${JSON.stringify(title)};\nexport const articleHtml = ${JSON.stringify(articleHtml)};\n`,
    "utf8",
  );
  indexLines.push(`import * as ${varName} from "./${slug}";`);
}

indexLines.push("");
indexLines.push("export const LEGAL_DOCUMENTS = {");
for (const slug of slugs) {
  const varName = slug.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const key = slug === "copyright" ? "copyright" : `"${slug}"`;
  indexLines.push(
    `  ${key}: { slug: "${slug}", title: ${varName}.title, articleHtml: ${varName}.articleHtml },`,
  );
}
indexLines.push("} as const;");
indexLines.push("");
indexLines.push("export type LegalSlug = keyof typeof LEGAL_DOCUMENTS;");
indexLines.push("export const LEGAL_SLUGS = Object.keys(LEGAL_DOCUMENTS) as LegalSlug[];");

fs.writeFileSync(path.join(outDir, "index.ts"), indexLines.join("\n"), "utf8");
console.log("[generate-legal-content] wrote", slugs.length, "files to src/content/legal/");
